#!/usr/bin/env python3
"""Build the admin SPA into dist/.

    python3 build.py            production build; needs SUPABASE_ANON_KEY in the environment
    python3 build.py --mock     build pointed at the local mock (scripts/mock_functions.mjs)

Copies public/ verbatim (no bundling), adds the logo, writes js/config.js and _headers.
"""
import argparse
import json
import os
import shutil
import sys
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent
PUBLIC = ROOT / "public"
LOGO = ROOT / "assets" / "APS_LOGO.png"
SHARED_SRC = ROOT / "supabase" / "functions" / "_shared"
SHARED_COPY = PUBLIC / "js" / "shared"
# Plain-JS modules the browser imports byte-identical to the Edge Functions' copies.
SHARED = ["settings_schema.js", "email_domain.js"]
DEFAULT_URL = "https://rtqitjlpwkubdiakhiqu.supabase.co"
MOCK_ORIGIN = "http://localhost:8001"


def headers(connect_origin, https):
    csp = "; ".join([
        "default-src 'none'",
        "script-src 'self'",
        "style-src 'self' https://fonts.googleapis.com",
        "font-src https://fonts.gstatic.com",
        "img-src 'self' data:",
        "connect-src %s" % connect_origin,
        "base-uri 'none'",
        "form-action 'self'",
        "frame-ancestors 'none'",
        "manifest-src 'self'",
    ] + (["upgrade-insecure-requests"] if https else []))
    lines = [
        "/*",
        "  Content-Security-Policy: %s" % csp,
        "  X-Robots-Tag: noindex, nofollow, noarchive",
        "  X-Content-Type-Options: nosniff",
        "  X-Frame-Options: DENY",
        "  Referrer-Policy: no-referrer",
        "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
        "  Cross-Origin-Opener-Policy: same-origin",
    ]
    if https:
        lines.append("  Strict-Transport-Security: max-age=31536000; includeSubDomains")
    lines += [
        "",
        "/",
        "  Cache-Control: no-cache",
        "/index.html",
        "  Cache-Control: no-cache",
        "/js/*",
        "  Cache-Control: no-cache",
        "/css/*",
        "  Cache-Control: no-cache",
        "/APS_LOGO.png",
        "  Cache-Control: public, max-age=604800",
        "",
    ]
    return "\n".join(lines)


def sync_shared():
    """The browser copies of the shared modules must be byte-identical to the server's."""
    for name in SHARED:
        src, copy = (SHARED_SRC / name).read_bytes(), SHARED_COPY / name
        if not copy.exists() or copy.read_bytes() != src:
            copy.parent.mkdir(parents=True, exist_ok=True)
            copy.write_bytes(src)
            print("synced public/js/shared/%s from supabase/functions/_shared/" % name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mock", action="store_true", help="point at the local mock backend")
    ap.add_argument("--mock-origin", default=MOCK_ORIGIN)
    ap.add_argument("--out", default="dist")
    args = ap.parse_args()

    if args.mock:
        url, key = args.mock_origin, "mock-anon-key"
    else:
        url = os.environ.get("SUPABASE_URL", DEFAULT_URL).rstrip("/")
        key = os.environ.get("SUPABASE_ANON_KEY", "")
        if not key:
            sys.exit("build.py: SUPABASE_ANON_KEY is not set. (Use --mock for a local build.)")
        if not url.startswith("https://"):
            sys.exit("build.py: SUPABASE_URL must be https.")

    sync_shared()
    domain = os.environ.get("ALLOWED_EMAIL_DOMAIN", "").strip() or None
    out = (ROOT / args.out).resolve()
    if ROOT not in out.parents:
        sys.exit("build.py: --out must be inside the repo")
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(PUBLIC, out)
    shutil.copy2(LOGO, out / "APS_LOGO.png")

    (out / "js" / "config.js").write_text(
        "// Generated by build.py. The anon key is public by design; every table the admin\n"
        "// touches has RLS with no anon policies, and every Edge Function re-checks the role.\n"
        "export const SUPABASE_URL = %s;\nexport const SUPABASE_ANON_KEY = %s;\nexport const MOCK = %s;\n"
        "// null = the default in shared/email_domain.js. Same variable the Edge Functions read.\n"
        "export const ALLOWED_EMAIL_DOMAIN = %s;\n"
        % (json.dumps(url), json.dumps(key), "true" if args.mock else "false", json.dumps(domain))
    )
    origin = "%s://%s" % (urlparse(url).scheme, urlparse(url).netloc)
    (out / "_headers").write_text(headers(origin, not args.mock))
    files = sum(1 for p in out.rglob("*") if p.is_file())
    print("built %s (%d files) → %s%s" % (out.relative_to(ROOT), files, origin, " [mock]" if args.mock else ""))


if __name__ == "__main__":
    main()
